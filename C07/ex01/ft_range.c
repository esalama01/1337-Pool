#include<stdlib.h>

int	*ft_range(int min, int max)
{
	int	l;
	int	*arr;
	int	i;

	l = max - min;
	if (min >= max)
		return (NULL);
	arr = (int *)malloc(l * sizeof(int));
	if (arr == NULL)
		return (NULL);
	i = 0;
	while (min < max)
	{
		arr[i] = min;
		min++;
		i++;
	}
	return (arr);
}
